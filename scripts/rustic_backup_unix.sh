#  FILE     : rustic_backup_unix.sh
#  DESCRIPTION : Runs rustic backup, prune, and integrity check (Linux/macOS)
# --------------------------------------------------------------------------------
#  README
# --------------------------------------------------------------------------------
#  PURPOSE
#
#    Executes a full Rustic backup cycle on Linux and macOS: runs a backup
#    against the configured repository, applies retention policy with prune,
#    and performs a partial integrity check on the repository. Reads all
#    configuration from /etc/rustic/rustic.toml. Intended to be run on a
#    schedule (systemd timer or launchd plist) or invoked directly via
#    SuperOps RMM.
#
#  DATA SOURCES & PRIORITY
#
#    - /etc/rustic/rustic.toml — all backend, repository, and backup settings
#    - /usr/local/bin/rustic   — rustic binary
#
#  REQUIRED INPUTS
#
#    No runtime variables. All configuration is read from the TOML file
#    generated by rustic_install_unix.sh.
#
#  SETTINGS
#
#    Hardcoded paths:
#      - Binary : /usr/local/bin/rustic
#      - Config : /etc/rustic/rustic.toml
#
#    Integrity check scope: --read-data-subset=1/100 (1% of data per run)
#
#  BEHAVIOR
#
#    The script performs the following actions in order:
#    1. Verifies that the rustic binary and config file exist
#    2. Exports RUSTIC_CONFIG_FILE to direct rustic to the TOML config
#    3. Runs rustic backup — fatal if it fails
#    4. Runs rustic forget --prune (retention policy) — warns if it fails
#    5. Runs rustic check --read-data-subset=1/100 (integrity) — warns if fails
#    6. Reports total duration and exits 0
#
#  PREREQUISITES
#
#    - Linux or macOS
#    - Root privileges (runs as root via RMM)
#    - rustic installed at /usr/local/bin/rustic
#    - /etc/rustic/rustic.toml configured by rustic_install_unix.sh
#    - Network access to the configured backup backend
#
#  SECURITY NOTES
#
#    - No credentials are printed to console output
#    - All secrets remain in the TOML config file (chmod 600)
#
#  EXIT CODES
#
#    0 = Success
#    1 = Failure (binary/config missing, or backup step failed)
#
#  EXAMPLE RUN
#
#    [INFO] RUSTIC BACKUP
#    ==============================================================
#      Binary : /usr/local/bin/rustic
#      Config : /etc/rustic/rustic.toml
#
#    [RUN] BACKUP
#    ==============================================================
#      snapshot abc12345 saved
#
#    [RUN] RETENTION
#    ==============================================================
#      applying retention policy
#      removed 2 snapshots
#
#    [RUN] INTEGRITY CHECK
#    ==============================================================
#      checking repository structure
#      check completed
#
#    [OK] FINAL STATUS
#    ==============================================================
#      Result   : SUCCESS
#      Duration : 42s
#
#    [OK] SCRIPT COMPLETE
