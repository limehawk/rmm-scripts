set -euo pipefail

# ==== HARDCODED PATHS ====
RUSTIC_BIN="/usr/local/bin/rustic"
CONFIG_FILE="/etc/rustic/rustic.toml"

# ==== TIMER ====
START_TIME="$(date +%s)"

# ==== PRE-FLIGHT CHECKS ====
if [[ ! -x "${RUSTIC_BIN}" ]]; then
    echo "[ERROR] PREFLIGHT CHECK"
    echo "=============================================================="
    echo "  rustic binary not found or not executable: ${RUSTIC_BIN}"
    echo "  Run rustic_install_unix.sh to install rustic first."
    echo ""
    echo "[ERROR] SCRIPT COMPLETE"
    echo "=============================================================="
    exit 1
fi

if [[ ! -f "${CONFIG_FILE}" ]]; then
    echo "[ERROR] PREFLIGHT CHECK"
    echo "=============================================================="
    echo "  Config file not found: ${CONFIG_FILE}"
    echo "  Run rustic_install_unix.sh to generate the configuration."
    echo ""
    echo "[ERROR] SCRIPT COMPLETE"
    echo "=============================================================="
    exit 1
fi

# ==== EXPORT CONFIG PATH ====
export RUSTIC_CONFIG_FILE="${CONFIG_FILE}"

# ==== INFO ====
echo ""
echo "[INFO] RUSTIC BACKUP"
echo "=============================================================="
echo "  Binary : ${RUSTIC_BIN}"
echo "  Config : ${CONFIG_FILE}"

# ==== BACKUP ====
echo ""
echo "[RUN] BACKUP"
echo "=============================================================="
"${RUSTIC_BIN}" backup 2>&1 | sed 's/^/  /'
# set -e ensures this exits 1 if backup fails

# ==== RETENTION ====
echo ""
echo "[RUN] RETENTION"
echo "=============================================================="
if "${RUSTIC_BIN}" forget --prune 2>&1 | sed 's/^/  /'; then
    echo "  Retention policy applied successfully"
else
    echo ""
    echo "[WARN] RETENTION"
    echo "=============================================================="
    echo "  rustic forget --prune failed — snapshots may not have been pruned"
    echo "  Review output above. Backup data is intact."
fi

# ==== INTEGRITY CHECK ====
echo ""
echo "[RUN] INTEGRITY CHECK"
echo "=============================================================="
if "${RUSTIC_BIN}" check --read-data-subset=1/100 2>&1 | sed 's/^/  /'; then
    echo "  Integrity check passed"
else
    echo ""
    echo "[WARN] INTEGRITY CHECK"
    echo "=============================================================="
    echo "  rustic check failed — repository may have integrity issues"
    echo "  Review output above. Consider running a full check manually."
fi

# ==== DURATION ====
END_TIME="$(date +%s)"
DURATION=$(( END_TIME - START_TIME ))

# ==== FINAL STATUS ====
echo ""
echo "[OK] FINAL STATUS"
echo "=============================================================="
echo "  Result   : SUCCESS"
echo "  Duration : ${DURATION}s"

echo ""
echo "[OK] SCRIPT COMPLETE"
echo "=============================================================="
exit 0
